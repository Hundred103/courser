CREATE TABLE quiz_ranking_attempts (
    id UUID PRIMARY KEY,
    ranking_version_id UUID NOT NULL REFERENCES quiz_ranking_versions (id) ON DELETE CASCADE,
    user_id BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    started_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    completed_at TIMESTAMP(6) WITHOUT TIME ZONE,
    status VARCHAR(16) NOT NULL DEFAULT 'STARTED'
);

CREATE TABLE quiz_ranking_entries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ranking_version_id UUID NOT NULL REFERENCES quiz_ranking_versions (id) ON DELETE CASCADE,
    user_id BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    score_scaled INTEGER NOT NULL,
    max_score_scaled INTEGER NOT NULL,
    duration_ms BIGINT NOT NULL,
    completed_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    CONSTRAINT uk_quiz_ranking_entries_user UNIQUE (ranking_version_id, user_id)
);

CREATE INDEX idx_quiz_ranking_entries_version ON quiz_ranking_entries (ranking_version_id);
